export function getMockPitch(leadId: string): SalesPitch | null {
  const lead = mockLeads.find(l => l.id === leadId);
  if (!lead) return null;

  const painPoints = lead.problems
    .filter(p => p.severity !== 'good')
    .slice(0, 3)
    .map(p => {
      if (p.severity === 'critical') return `${p.title} (${p.impact})`;
      return `${p.title} — ${p.impact}`;
    });

  return {
    whyThisLead: [
      `Strong demand: ${lead.rating}★ reviews, ${lead.reviewCount} reviews`,
      `Technical gaps: ${lead.problems.filter(p => p.severity === 'critical').map(p => p.title).join(', ')}`,
      `Competitor weakness: ${lead.competitorSignals}`,
    ],
    topPainPoints: painPoints,
    yourAngle: `We help ${lead.category.toLowerCase()} businesses like ${lead.businessName} improve their digital presence and customer acquisition. Average clients see 15-20% increase in bookings within the first month.`,
    generatedMessage: `Hi,

I came across ${lead.businessName} while researching ${lead.category.toLowerCase()} businesses in ${lead.location}. Your ${lead.rating}★ rating with ${lead.reviewCount} reviews shows you're clearly doing great work.

I noticed a few areas where your online presence could be capturing more customers:

${lead.problems.filter(p => p.severity === 'critical').map(p => `• ${p.title} — ${p.impact}`).join('\n')}

We've helped similar ${lead.category.toLowerCase()} businesses address these exact issues, typically generating 15-20 additional bookings per month.

Would you be open to a quick 15-minute call to discuss how we could help ${lead.businessName}?

Best regards`,
  };
}
